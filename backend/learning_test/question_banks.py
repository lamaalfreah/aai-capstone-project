def get_questions_for_age(age_group):
    banks = QUESTION_BANKS.get(age_group) or QUESTION_BANKS["15plus"]
    return random.choice(banks)


def calculate_style_from_answers(answers):
    counts = {"visual": 0, "auditory": 0, "reading": 0, "kinesthetic": 0}

    for answer in answers:
        value = answer.get("selected_value") or answer.get("answer")
        if value in counts:
            counts[value] += 1

    winner = max(counts, key=counts.get)

    summaries = {
        "visual": "يميل نمطك إلى التعلم البصري؛ تستفيد أكثر من المخططات، الصور، الألوان، والخرائط الذهنية.",
        "auditory": "يميل نمطك إلى التعلم السمعي؛ تستفيد أكثر من الشرح الصوتي، النقاش، والتكرار المسموع.",
        "reading": "يميل نمطك إلى التعلم القرائي/الكتابي؛ تستفيد أكثر من الملخصات، القوائم، والملاحظات المكتوبة.",
        "kinesthetic": "يميل نمطك إلى التعلم الحركي/التطبيقي؛ تستفيد أكثر من التجربة، التمارين، والتطبيق العملي.",
    }

    return {
        "learning_style": STYLE_LABELS.get(winner, "بصري"),
        "ai_summary": summaries.get(winner, summaries["visual"]),
        "scores": counts,
    }
